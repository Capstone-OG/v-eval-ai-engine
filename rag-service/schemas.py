class GenerateExamRequest(BaseModel):
    """Payload to trigger AI exam generation."""

    prompt: Optional[str] = Field(
        default="Đề thi khảo sát năng lực chuẩn hóa V-ACT tích hợp 5 lĩnh vực: Giải tích & Thống kê ứng dụng, Suy luận logic suy diễn, Đọc hiểu văn bản học thuật và Khoa học ứng dụng thực tiễn.",
        description="Custom guidance or focus topic for the exam generator",
    )
    domain_id: Optional[str] = Field(
        default="ALL",
        description="Domain ID filter (e.g., dom_math, dom_logic, or ALL)",
    )
    question_count: int = Field(
        default=30,
        ge=5,
        le=50,
        description="Number of questions to generate (default 30)",
    )
    bloom_level: Optional[int] = Field(
        default=None,
        ge=1,
        le=6,
        description="Specific Bloom taxonomy level (1..6) or None for balanced distribution",
    )
    difficulty_style: Optional[str] = Field(
        default="BALANCED",
        description="BALANCED, BASIC (1-2), INTERMEDIATE (3-4), ADVANCED (5-6)",
    )
    generator_mode: Optional[str] = Field(
        default="gemini",
        description="Generator engine mode: 'gemini' for real-time Gemini Cloud generation, 'fast' for in-memory calibrated bank",
    )


class GeneratedQuestionItem(BaseModel):
    """Individual multiple-choice question generated by AI."""

    id: str = Field(..., description="Unique question identifier (e.g., q01)")
    domain_id: str = Field(..., description="Domain ID")
    domain_name: str = Field(..., description="Human readable domain name")
    skill_id: str = Field(..., description="Skill ID")
    skill_name: str = Field(..., description="Human readable skill name")
    bloom: int = Field(..., ge=1, le=6, description="Bloom taxonomy level 1..6")
    content: str = Field(..., description="LaTeX-enabled question content")
    options: list[str] = Field(..., min_length=4, max_length=4, description="Four options A, B, C, D")
    correct: str = Field(..., pattern="^[A-D]$", description="Correct option key (A, B, C, or D)")
    explanation: Optional[str] = Field(default="", description="Pedagogical explanation for the correct answer")


class GenerateExamResponse(BaseModel):
    """Response returned when AI finishes generating an exam."""

    title: str = Field(..., description="Title of the generated exam")
    prompt_used: str = Field(..., description="Effective prompt utilized")
    total_questions: int = Field(..., description="Total questions produced")
    questions: list[GeneratedQuestionItem] = Field(..., description="List of generated questions")
    bloom_distribution: dict[str, int] = Field(default_factory=dict, description="Count of questions per Bloom level")
    option_distribution: dict[str, int] = Field(default_factory=dict, description="Count of correct keys (A, B, C, D)")
    engine_used: str = Field(default="gemini_cloud", description="'gemini_cloud' or 'fast_calibrated'")
    generation_time_ms: int = Field(default=0, description="Time taken to generate the exam in milliseconds")

