"""
schemas.py — Pydantic Request & Response Models
================================================
Defines structured schemas for the FastAPI REST API with Document Versioning
and Soft Delete support.
"""

from __future__ import annotations

from typing import Any, Optional
from pydantic import BaseModel, Field


# ---------------------------------------------------------------------------
# Chat Schemas
# ---------------------------------------------------------------------------


class ChatRequest(BaseModel):
    """Payload for conversational question answering."""

    question: str = Field(
        ...,
        min_length=1,
        description="The natural language question to ask the AI.",
        examples=["Công ty ABC được thành lập khi nào?"],
    )
    session_id: str = Field(
        default="default",
        min_length=1,
        description="Session identifier for multi-turn conversational memory.",
        examples=["default", "user-123"],
    )


class DocumentSource(BaseModel):
    """Metadata and excerpt of a retrieved reference document."""

    source: str = Field(..., description="Origin of the chunk (file name, title, etc.)")
    file_name: str | None = Field(default=None, description="Logical file name")
    version: int | None = Field(default=None, description="Document version number")
    document_id: str | None = Field(default=None, description="Physical version ID")
    doc_type: str | None = Field(default=None, description="Document type (pdf, docx, text)")
    page: int | str | None = Field(default=None, description="Page number if applicable")
    chunk_index: int | None = Field(default=None, description="Index of the chunk in document")
    content_snippet: str = Field(..., description="Excerpt of the retrieved context chunk")


class ChatResponse(BaseModel):
    """Response returned by the non-streaming chat endpoint."""

    session_id: str = Field(..., description="Active session ID")
    question: str = Field(..., description="The user's original question")
    answer: str = Field(..., description="Grounded response generated by Gemini")
    sources: list[DocumentSource] = Field(
        default_factory=list,
        description="List of relevant document chunks retrieved from pgvector",
    )


class SessionListResponse(BaseModel):
    """List of active in-memory session IDs."""

    active_sessions: list[str] = Field(..., description="All currently active session identifiers")


class SessionClearResponse(BaseModel):
    """Confirmation when a session's history is cleared."""

    session_id: str
    message: str


# ---------------------------------------------------------------------------
# Document Ingestion & Versioning Schemas
# ---------------------------------------------------------------------------


class TextIngestRequest(BaseModel):
    """Payload for direct plain-text ingestion."""

    title: str = Field(
        default="custom_document",
        min_length=1,
        description="Logical document title/name used for version grouping.",
        examples=["chinh_sach_cong_ty"],
    )
    content: str = Field(
        ...,
        min_length=1,
        description="Raw text content to store into the knowledge base.",
        examples=["V-Act là một hệ thống đánh giá hoạt động dựa trên AI."],
    )


class IngestResponse(BaseModel):
    """Response returned after processing or triggering document ingestion."""

    message: str = Field(..., description="Status message")
    status: str = Field(
        ...,
        description="Ingestion status: READY, PROCESSING, UNCHANGED, or FAILED",
        examples=["READY", "PROCESSING", "UNCHANGED"],
    )
    document_id: str = Field(..., description="Physical document version ID (UUID)")
    document_group_id: str = Field(..., description="Logical document group ID (UUID)")
    file_name: str = Field(..., description="Logical file or document title")
    version: int = Field(..., description="Version number (1, 2, 3...)")
    file_hash: str = Field(..., description="SHA-256 content checksum")
    chunks_ingested: int = Field(default=0, description="Number of vector chunks generated")


class DocumentVersionItem(BaseModel):
    """Metadata of a single physical document version."""

    id: str = Field(..., description="Physical document ID (UUID)")
    document_group_id: str = Field(..., description="Logical document group ID (UUID)")
    file_name: str = Field(..., description="File name or document title")
    version: int = Field(..., description="Version number")
    file_hash: str = Field(..., description="SHA-256 hash")
    status: str = Field(..., description="Status (PENDING, PROCESSING, READY, FAILED)")
    is_current: bool = Field(..., description="True if this version is actively served to RAG")
    total_chunks: int = Field(..., description="Total vector chunks in database")
    created_at: str = Field(..., description="Creation timestamp ISO")
    error_message: str | None = Field(default=None, description="Error reason if FAILED")


class DocumentGroupItem(BaseModel):
    """Logical document summary with active version details."""

    document_group_id: str = Field(..., description="Logical document group ID")
    file_name: str = Field(..., description="Document file name")
    active_version: int | None = Field(default=None, description="Currently active version number")
    active_document_id: str | None = Field(default=None, description="ID of currently active version")
    total_versions: int = Field(..., description="Total number of versions uploaded")
    status: str = Field(..., description="Status of active version")
    updated_at: str = Field(..., description="Last update timestamp ISO")


class RollbackRequest(BaseModel):
    """Payload to rollback a logical document to a previous version."""

    version: int = Field(..., ge=1, description="The target version number to restore")


class ActionResponse(BaseModel):
    """Generic status response for rollback, delete, and purge actions."""

    message: str
    document_group_id: str
    action: str
    target_version: int | None = None


class DocStatsResponse(BaseModel):
    """Statistics of stored documents in the catalog and vector store."""

    total_chunks: int = Field(..., description="Total chunks in document_chunks table")
    active_chunks: int = Field(..., description="Active chunks serving RAG queries")
    total_logical_documents: int = Field(..., description="Unique logical documents")
    total_versions: int = Field(..., description="Total physical document records in catalog")
    table_name: str = Field(..., description="Vector collection table name")
    embedding_dimensions: int = Field(..., description="Dimensions of vector embeddings")


# ---------------------------------------------------------------------------
# System / Health Schemas
# ---------------------------------------------------------------------------


class HealthResponse(BaseModel):
    """Health check status and system configuration."""

    status: str = Field(..., description="Overall service status (healthy / degraded)")
    database: str = Field(..., description="PostgreSQL + pgvector connection status")
    llm_model: str = Field(..., description="Configured Gemini chat model")
    embedding_model: str = Field(..., description="Configured Gemini embedding model")
    total_active_chunks: int = Field(..., description="Active vector chunks currently serving RAG")
    total_documents: int = Field(..., description="Total logical documents in catalog")


# ---------------------------------------------------------------------------
# Diagnostic Analysis Schemas (Core Flow 1 — Step 4)
# ---------------------------------------------------------------------------


class DiagnosticAnswerItem(BaseModel):
    """A single student answer from the 30-question diagnostic test."""

    question_id: str = Field(..., description="UUID of the question")
    skill_id: str = Field(..., description="UUID of the skill this question tests")
    domain_id: str = Field(
        default="",
        description="UUID of the competency domain. If empty, server looks it up.",
    )
    difficulty_level: int = Field(
        ..., ge=1, le=6,
        description=(
            "Bloom's Taxonomy Level (1–6): "
            "1=Remembering, 2=Understanding, 3=Applying, "
            "4=Analyzing, 5=Evaluating, 6=Creating"
        ),
    )
    is_correct: bool = Field(..., description="Whether the student answered correctly")
    time_spent_seconds: int = Field(
        ..., ge=0,
        description="Time the student spent on this question (seconds)",
    )


class DiagnosticDomainName(BaseModel):
    """Mapping of domain_id to display name."""

    domain_id: str = Field(..., description="UUID of the competency domain")
    domain_name: str = Field(..., description="Display name (e.g. 'Toán học & Giải tích')")


class DiagnosticAnalyzeRequest(BaseModel):
    """Request payload for POST /api/v1/diagnostic/analyze."""

    student_id: str = Field(..., description="UUID of the student")
    submission_id: str = Field(..., description="UUID of the diagnostic submission")
    target_score: int = Field(
        default=800, ge=0, le=1200,
        description="Student's target V-ACT score (0–1200, default 800)",
    )
    answers: list[DiagnosticAnswerItem] = Field(
        ..., min_length=1,
        description="List of 30 diagnostic test answers",
    )
    domain_names: list[DiagnosticDomainName] = Field(
        default_factory=list,
        description="Optional domain_id → name mapping for radar chart labels",
    )
    all_skill_ids: dict[str, str] = Field(
        default_factory=dict,
        description=(
            "Optional full mapping skill_id → domain_id for ALL skills in the system. "
            "Skills not in the answers list will receive inferred P(L0) from parent domain."
        ),
    )


class DiagnosticSkillPriorDto(BaseModel):
    """BKT prior P(L0) for a single skill."""

    skill_id: str = Field(..., description="UUID of the skill")
    domain_id: str = Field(..., description="UUID of the parent competency domain")
    theta_skill: float = Field(..., description="Skill-level ability estimate on IRT scale")
    p_l0: float = Field(
        ..., ge=0.0, le=1.0,
        description="BKT prior P(L0) = Sigmoid(theta_skill), clamped to [0.05, 0.95]",
    )
    source: str = Field(
        ...,
        description="'measured' (had questions) or 'inferred_from_domain' (no questions)",
    )


class DiagnosticDomainScoreDto(BaseModel):
    """Aggregated analysis for one competency domain."""

    domain_id: str = Field(..., description="UUID of the domain")
    domain_name: str = Field(..., description="Display name of the domain")
    theta_domain: float = Field(..., description="Domain-level ability estimate")
    total_questions: int = Field(..., description="Number of questions in this domain")
    correct_count: int = Field(..., description="Number of correct answers")
    accuracy_pct: float = Field(..., description="Accuracy percentage [0–100]")


class DiagnosticRadarAxisDto(BaseModel):
    """One axis of the radar chart comparing student vs benchmark."""

    domain_id: str = Field(..., description="UUID of the domain")
    domain_name: str = Field(..., description="Display name of the domain")
    student_pct: float = Field(..., description="Student's accuracy percentage [0–100]")
    benchmark_pct: float = Field(..., description="Target benchmark percentage [0–100]")


class DiagnosticAnalyzeResponse(BaseModel):
    """Full response from the diagnostic analysis engine."""

    student_id: str = Field(..., description="UUID of the student")
    submission_id: str = Field(..., description="UUID of the diagnostic submission")
    theta_0: float = Field(
        ...,
        description="Overall ability estimate on IRT scale [-3.0, +3.0]",
    )
    placement_class: str = Field(
        ...,
        description=(
            "Recommended class level: "
            "'FOUNDATION' (theta < -0.5), "
            "'ACCELERATION' (-0.5 ≤ theta ≤ +0.5), "
            "'BREAKTHROUGH' (theta > +0.5)"
        ),
    )
    domain_scores: list[DiagnosticDomainScoreDto] = Field(
        ..., description="Per-domain ability breakdown",
    )
    skill_priors: list[DiagnosticSkillPriorDto] = Field(
        ..., description="BKT prior P(L0) for each skill",
    )
    radar_chart: list[DiagnosticRadarAxisDto] = Field(
        ..., description="Radar chart coordinates for frontend rendering",
    )
    ai_commentary: str = Field(
        default="",
        description="AI-generated brief Socratic commentary on student's strengths/weaknesses",
    )


